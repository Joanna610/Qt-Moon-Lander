unsigned short int ComputeCRC8(char* pData, int Length, unsigned int Poly, unsigned short int InitVal)
{
    unsigned short int ResCRC = InitVal;

    while (--Length >= 0) {
        ResCRC ^= *pData++;
        for (short int i=0; i < 8; ++i)
            ResCRC = ResCRC & 0x80 ? (ResCRC << 1) ^ Poly : ResCRC << 1;
    }
    return ResCRC & 0xFF;
}
